const hitterLabels=['Hit','Raw power','Game power','Run','Arm','Field'];
const pitcherLabels=['Fastball','Slider','Curveball','Changeup','Splitter','Control'];
const esc=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const pct=grade=>grade==null?0:Math.max(0,Math.min(100,(Number(grade)-20)/60*100));
const tone=grade=>grade==null?'missing':grade>=60?'plus':grade>=45?'average':'below';

export function pipelineJ15GradesCard(player){
  const row=j15PipelineGrades[player?.id];
  if(!row)return '';
  const labels=row.type==='P'?pitcherLabels:hitterLabels;
  const hasAny=row.fv!=null||row.g.some(v=>v!=null);
  const header=`<div class="pipeline-grade-heading"><div><span class="pipeline-grade-kicker">BANGALANGIN PIPELINE</span><h2>Projected scouting grades</h2></div><span class="pipeline-grade-confidence">${esc(row.c==='Insufficient evidence'?'Evidence limited':row.c+' confidence')}</span></div>`;
  if(!hasAny)return `<section class="pipeline-grade-card pipeline-grade-card--empty" aria-label="Projected scouting grades">${header}<p class="pipeline-grade-empty">Not graded yet</p><p class="pipeline-grade-note">The available amateur evidence is not strong enough to assign defensible 20–80 tool grades. Pipeline leaves those values blank rather than estimating from bonus size or ranking position.</p></section>`;
  const tools=labels.map((label,index)=>[label,row.g[index]]);
  tools.push(['Overall FV',row.fv]);
  const rows=tools.map(([label,grade])=>`<div class="pipeline-grade-row ${grade==null?'is-missing':''}"><span class="pipeline-grade-label">${esc(label)}</span><div class="pipeline-grade-track" aria-hidden="true"><i class="pipeline-grade-fill pipeline-grade-fill--${tone(grade)}" style="width:${pct(grade)}%"></i></div><b class="pipeline-grade-value">${grade==null?'—':esc(grade)}</b></div>`).join('');
  return `<section class="pipeline-grade-card" aria-label="Projected scouting grades">${header}<div class="pipeline-grade-grid">${rows}</div><p class="pipeline-grade-note">Projected future grades on the 20–80 scouting scale. Missing tools are intentionally left ungraded where the available evidence is insufficient.</p></section>`;
}
